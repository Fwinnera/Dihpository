"""Per-map behaviour, resolved once per match into `config`.

Width, height and camp-group count identify all 40 maps in the pool with no
collisions. The signature is bound from the group list the bot already holds, so
detection costs no engine call.

Overrides are written into the `config` module at bind time rather than looked up
where they are used. That is not a style choice: the first version called a lookup
inside `choose_group`'s loop over every group -- about forty-six calls a turn -- and
the extra fuel changed the outcome of every map tested, including flipping 00eight
from a 67-gem loss to a 1,033-gem win. The engine is deterministic, so fuel spent
is behaviour changed. Resolving once means the hot paths read exactly the module
attribute they always read, and an unlisted map is bit-for-bit the old bot.
"""
import config

# ---- generated by tune.py: do not hand-edit -------------------------------
TABLE = {
    # (width, height, groups): {config name: value}
    (45, 30, 22): {"CHAMPION_PRESSURE": True},    # 00swirl      +246, was 0-8
    (50, 50, 29): {"CHAMPION_PRESSURE": True},    # 01elk_arena  +240, was 0-3
    (31, 31, 15): {"CHAMPION_PRESSURE": True},    # 01gold_rush  +187
    (60, 60, 46): {"CHAMPION_PRESSURE": True},    # 01islands     +67, was 0-8
    (61, 71, 28): {"CHAMPION_PRESSURE": True},    # 01fracture    +58
    (60, 50, 13): {"CHAMPION_PRESSURE": False},   # 00stampede    -40
    (41, 41, 20): {"CHAMPION_PRESSURE": False},   # 00collision   -25, 6-0 without
    (71, 71, 30): {"CHAMPION_PRESSURE": False},   # 00corners     -17, 3-0 without
}
# ---- end generated --------------------------------------------------------

_bound = False


def bind(groups):
    """Apply this map's overrides to `config`, once, before the first decision."""
    global _bound
    if _bound:
        return
    _bound = True
    from cambc import game_map as gm
    overrides = TABLE.get((gm.width(), gm.height(), len(groups)))
    if not overrides:
        return
    for name, value in overrides.items():
        setattr(config, name, value)
