#!/usr/bin/env python3
"""Fight danger learned from logged games: P(this champion dies within 15 rounds | state).

    dzfit.py RUNDIR [--emit HEADER]

RUNDIR holds profrun.sh bundles of the `dzlog` bot (ab3 plus one `DZ` line per living
turn and a `DZD` line per dead turn; folders <opp>__<map>__<A|B>, dzlog on side A or B).
State per turn: health fraction, local odds (our total health x strength with allies
within 5, against the enemies' within 6, as a log ratio), enemies within 6, allies within
5, steps from home. Prints the death rate by cell and, with --emit, writes a C++ header
with the table for the bot (`danger::table`).
"""
import collections
import math
import sys
import zipfile
from pathlib import Path

run = Path(sys.argv[1])
emit = sys.argv[sys.argv.index("--emit") + 1] if "--emit" in sys.argv else None
HORIZON = 15


def bins(hp, mx, ne, eh, es, na, ah, as_, strength, home):
    frac = hp / max(1.0, mx)
    hb = 0 if frac < 0.2 else 1 if frac < 0.35 else 2 if frac < 0.5 else 3 if frac < 0.75 else 4
    if ne == 0:
        ob = 0
    else:
        ours = (hp + ah) * (max(1.0, strength) + as_)
        ratio = math.log(max(1.0, ours) / max(1.0, eh * max(1.0, es)))
        ob = 1 if ratio < -1.0 else 2 if ratio < -0.3 else 3 if ratio < 0.3 else 4 if ratio < 1.0 else 5
    nb = min(ne, 3)
    ab = min(na, 2)
    fb = 0 if home <= 8 else 1
    return hb, ob, nb, ab, fb


cells = collections.defaultdict(lambda: [0, 0])  # cell -> [turns, deaths within HORIZON]
games = 0
for d in sorted(run.iterdir()):
    if not d.is_dir():
        continue
    side = d.name.rsplit("__", 1)[-1]
    bundle = next(d.glob("*.repl26a"), None)
    if bundle is None:
        continue
    try:
        text = zipfile.ZipFile(bundle).read(f"team-{side.lower()}.stdout").decode("utf8", "replace")
    except KeyError:
        continue
    games += 1
    alive = collections.defaultdict(list)  # slot -> [(round, cell)]
    deaths = collections.defaultdict(list)  # slot -> rounds of first dead turn
    dead_now = set()
    for raw in text.splitlines():
        line = raw.replace("\x00", "").strip()
        f = line.split()
        if not f:
            continue
        if f[0] == "DZ" and len(f) == 15:
            try:
                r, slot = int(f[1]), int(f[2])
                hp, mx, st, gems, ne, eh, es, na, ah, as_, near, home = map(float, f[3:15])
            except ValueError:
                continue
            dead_now.discard(slot)
            alive[slot].append((r, bins(hp, mx, int(ne), eh, es, int(na), ah, as_, st, home)))
        elif f[0] == "DZD" and len(f) == 3:
            try:
                r, slot = int(f[1]), int(f[2])
            except ValueError:
                continue
            if slot not in dead_now:
                deaths[slot].append(r)
                dead_now.add(slot)
    for slot, turns in alive.items():
        ds = sorted(deaths[slot])
        j = 0
        for r, cell in turns:
            while j < len(ds) and ds[j] <= r:
                j += 1
            died = j < len(ds) and ds[j] - r <= HORIZON
            c = cells[cell]
            c[0] += 1
            c[1] += died

total = sum(c[0] for c in cells.values())
print(f"{games} games, {total} living turns, {sum(c[1] for c in cells.values())} within {HORIZON} rounds of a death")
names = ["health", "odds", "enemies", "allies", "far"]
for k, label in enumerate(names):
    agg = collections.defaultdict(lambda: [0, 0])
    for cell, (n, dd) in cells.items():
        agg[cell[k]][0] += n
        agg[cell[k]][1] += dd
    print(f"  by {label}: " + "  ".join(f"{b}: {dd / max(1, n):.2f} ({n})" for b, (n, dd) in sorted(agg.items())))

if emit:
    # Shrink each cell toward its health x enemies parent so thin cells do not invent danger.
    parent = collections.defaultdict(lambda: [0, 0])
    for cell, (n, dd) in cells.items():
        parent[(cell[0], cell[2])][0] += n
        parent[(cell[0], cell[2])][1] += dd
    rows = []
    for hb in range(5):
        for ob in range(6):
            for nb in range(4):
                for ab in range(3):
                    for fb in range(2):
                        n, dd = cells.get((hb, ob, nb, ab, fb), (0, 0))
                        pn, pd = parent.get((hb, nb), (0, 0))
                        prior = pd / pn if pn else 0.0
                        rows.append((dd + 20 * prior) / (n + 20))
    out = Path(emit)
    out.write_text(
        "// Generated by analysis/rebuild/dzfit.py: P(death within 15 rounds) by state cell,\n"
        f"// from {games} logged games ({total} turns). Index: ((((health*6+odds)*4+enemies)*3+allies)*2+far).\n"
        "#pragma once\n\nnamespace danger {\n\ninline constexpr float table[720] = {\n"
        + ",\n".join("    " + ", ".join(f"{p:.4f}f" for p in rows[i:i + 12]) for i in range(0, len(rows), 12))
        + "\n};\n\n}  // namespace danger\n")
    print("wrote", out)
