#!/usr/bin/env python3
"""#1's draft per map, as a C++ table keyed by a map fingerprint apex can read in game.

#1 (prism best girl) drafts the same order on a map against every opponent, and
different orders on different maps. The fingerprint (width, height, number of
camp groups, total gems) is unique across the 40 maps. Writes
ws/bots/apex/src/draft_table.h from ws/bench/top1/matches.json; unseen maps
fall back to apex's default order.
"""
import collections
import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = ["ryth", "vesper_vale", "vendetta", "cassi_and_issac", "stellar", "prism", "marcella",
         "willow", "ren", "varg", "tavi", "heart_of_ruin"]


def main() -> None:
    camps = json.loads((ROOT / "ws/bench/camptable.json").read_text())
    dims = {}
    for f in glob.glob(str(ROOT / "ws/bench/h2h_apex_v100/*__*__A.json")):
        m = Path(f).stem.split("__")[1].replace("-", "_")
        d = json.loads(Path(f).read_text())
        dims[m] = (d["match"]["width"], d["match"]["height"])
    orders = collections.defaultdict(collections.Counter)
    for match in json.loads((ROOT / "ws/bench/top1/matches.json").read_text()):
        for team in match["teams"]:
            if team["name"] == "prism best girl":
                orders[match["map"]][tuple(team["draftPicks"])] += 1
    rows = []
    for m in sorted(orders):
        order, n = orders[m].most_common(1)[0]
        w, h = dims[m]
        groups = camps[m]
        gems = sum(g["gems"] for g in groups)
        picks = ", ".join(f"D::{NAMES[p]}" for p in order)
        rows.append(f"    {{{w}, {h}, {len(groups)}, {gems}, {{{picks}}}}},  // {m} ({n} of {sum(orders[m].values())})")
    text = (
        "// Generated by analysis/top1_drafts.py from #1's ranked games: do not edit.\n"
        "// #1's draft per map, keyed by (width, height, camp groups, total gems).\n"
        "#pragma once\n#include \"common.h\"\n\nnamespace draft {\n\n"
        "struct MapDraft {\n    int width, height, groups, gems;\n    std::vector<bc::champion_draft> order;\n};\n\n"
        "inline const std::vector<MapDraft>& top1_table() {\n    using D = bc::champion_draft;\n"
        "    static const std::vector<MapDraft> table{\n" + "\n".join(rows) + "\n    };\n    return table;\n}\n\n"
        "}  // namespace draft\n")
    (ROOT / "ws/bots/apex/src/draft_table.h").write_text(text)
    print(f"{len(rows)} maps written")


if __name__ == "__main__":
    main()
